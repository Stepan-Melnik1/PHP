<?php

// Простой пример программы на PHP

$names = ["Аня", "Борис", "Вика", "Дима"];

echo "Привет! Вот список участников:\n";

foreach ($names as $name) {
    echo "- $name\n";
}

$sum = 0;
for ($i = 1; $i <= 5; $i++) {
    $sum += $i;
}

echo "Сумма чисел от 1 до 5: $sum\n";

echo "Программа завершена.\n";
